import type { Metadata } from "next";
import Link from "next/link";
import { ArticleCard } from "@/components/cards/article-card";
import { Section } from "@/components/layout/container";
import { LibraryStage } from "@/components/library3d/library-stage";
import { MotionProvider, Reveal } from "@/components/motion/reveal";
import { NewsletterForm } from "@/components/newsletter/newsletter-form";
import { LinkButton } from "@/components/ui/button";
import { Eyebrow, Heading, Text } from "@/components/ui/typography";
import { getLatestArticles, getPublishedArticles } from "@/lib/blog/queries";
import { getFeaturedProducts, getPublishedProducts, getSpotlightProducts } from "@/lib/catalog/queries";
import { ProductCard } from "@/components/cards/product-card";
import { CountUp, Magnetic, Parallax } from "@/components/motion/effects";
import { getCategories } from "@/lib/categories/queries";
import { getSiteSettings } from "@/lib/settings/queries";
import { AdSlot } from "@/components/ads/ad-slot";
import { JsonLd } from "@/components/seo/json-ld";
import { siteUrl } from "@/lib/site-url";

// Set here, not in the root layout — a layout canonical would be inherited by every page.
export const metadata: Metadata = { alternates: { canonical: "/" } };

/**
 * Homepage — the six scenes of PRD §6.3.
 * Scenes 1–2 are the immersive 3D library (LibraryStage); Scenes 3–6 are calm editorial
 * sections with scroll reveals. No 3D sits behind long-form text.
 */
export default async function HomePage() {
  const [featured, allFeatured, articles, categories, settings, allBooks, allArticles] = await Promise.all([
    getSpotlightProducts(3),
    getFeaturedProducts(Infinity),
    getLatestArticles(3),
    getCategories(),
    getSiteSettings(),
    getPublishedProducts(),
    getPublishedArticles(),
  ]);
  const used = new Set([...allBooks.map((b) => b.category), ...allArticles.flatMap((a) => a.categories)]);
  const liveSubjects = categories.filter((c) => used.has(c.slug)).length;
  const stats = [
    { value: allBooks.length, label: allBooks.length === 1 ? "Book in the library" : "Books in the library" },
    { value: allArticles.length, label: allArticles.length === 1 ? "Article in the journal" : "Articles in the journal" },
    // Only subjects that actually have a published book or a live article.
    { value: liveSubjects, label: liveSubjects === 1 ? "Subject to explore" : "Subjects to explore" },
  ];

  const base = siteUrl();
  const structured = [
    {
      "@context": "https://schema.org",
      "@type": "Organization",
      "@id": `${base}/#organization`,
      name: settings.brandName,
      url: base,
      logo: `${base}/icon`, // generated by src/app/icon.tsx
      ...(settings.publisherName ? { founder: { "@type": "Person", name: settings.publisherName } } : {}),
      ...(settings.contactEmail ? { email: settings.contactEmail } : {}),
      ...(Object.values(settings.social).some(Boolean) ? { sameAs: Object.values(settings.social).filter(Boolean) } : {}),
    },
    {
      "@context": "https://schema.org",
      "@type": "WebSite",
      name: settings.brandName,
      url: base,
      publisher: { "@id": `${base}/#organization` },
      potentialAction: {
        "@type": "SearchAction",
        target: { "@type": "EntryPoint", urlTemplate: `${base}/books?q={search_term_string}` },
        "query-input": "required name=search_term_string",
      },
    },
  ];

  return (
    <MotionProvider>
      <JsonLd data={structured} />
      {/* Scenes 1–2: Library entrance + featured books */}
      <LibraryStage featured={featured} tagline={settings.tagline} description={settings.description} />

      {/* The library in numbers — figures count up as they come into view. */}
      <section aria-label="The library in numbers" className="glass relative rounded-none border-x-0">
        <ul className="mx-auto grid w-full max-w-content divide-line px-gutter sm:grid-cols-3 sm:divide-x">
          {stats.map((s, i) => (
            <Reveal as="li" key={s.label} delay={i * 0.1} className="flex flex-col items-center gap-2 py-10 text-center">
              <CountUp value={s.value} className="font-serif text-display leading-none text-gold-deep" />
              <span className="text-eyebrow font-medium uppercase tracking-[0.16em] text-muted">{s.label}</span>
            </Reveal>
          ))}
        </ul>
      </section>

      {/* Featured books — every book marked "featured" in the admin (the 3D scene above shows a few). */}
      {allFeatured.length > 0 && (
        <Section aria-labelledby="featured-heading">
          <Reveal className="mb-12 flex flex-wrap items-end justify-between gap-4">
            <div className="flex flex-col gap-3">
              <Eyebrow>From the shelves</Eyebrow>
              <Heading id="featured-heading" reveal>Featured books</Heading>
            </div>
            <LinkButton href="/books" variant="ghost" size="sm">
              View all books
            </LinkButton>
          </Reveal>
          <ul className="grid grid-cols-2 gap-x-6 gap-y-12 sm:grid-cols-3 lg:grid-cols-5">
            {allFeatured.map((p, i) => (
              <Reveal as="li" key={p.id} delay={(i % 5) * 0.06}>
                <ProductCard product={p} />
              </Reveal>
            ))}
          </ul>
        </Section>
      )}

      {/* Scene 3: Categories */}
      <Section tone="beige" aria-labelledby="categories-heading" className="relative">
        <Reveal className="mb-10 flex flex-col gap-3">
          <Eyebrow>Subjects</Eyebrow>
          <Heading id="categories-heading" reveal>Browse by category</Heading>
        </Reveal>
        <ul className="grid border-t border-line sm:grid-cols-2 lg:grid-cols-4">
          {categories.map((c, i) => (
            <Reveal
              as="li"
              key={c.slug}
              delay={(i % 4) * 0.06}
              className="border-b border-line sm:odd:border-r lg:border-r lg:[&:nth-child(4n)]:border-r-0"
            >
              <Link
                href={`/blog/category/${c.slug}`}
                className="group flex min-h-20 items-center justify-between px-1 font-serif text-h4 text-charcoal transition-colors hover:text-gold-deep sm:px-6"
              >
                {c.name}
                <span
                  aria-hidden
                  className="text-gold transition-transform duration-(--duration-base) ease-editorial group-hover:translate-x-1"
                >
                  →
                </span>
              </Link>
            </Reveal>
          ))}
        </ul>
      </Section>

      {/* Scene 4: Latest articles (hidden until at least one article is live) */}
      {articles.length > 0 && (
      <Section aria-labelledby="articles-heading">
        <Reveal className="mb-12 flex flex-wrap items-end justify-between gap-4">
          <div className="flex flex-col gap-3">
            <Eyebrow>Journal</Eyebrow>
            <Heading id="articles-heading" reveal>Latest articles</Heading>
          </div>
          <LinkButton href="/blog" variant="ghost" size="sm">
            View all articles
          </LinkButton>
        </Reveal>
        <ul className="grid gap-x-8 gap-y-14 md:grid-cols-2 lg:grid-cols-3">
          {articles.map((a, i) => (
            <Reveal as="li" key={a.id} delay={i * 0.08}>
              <ArticleCard article={a} />
            </Reveal>
          ))}
        </ul>
      </Section>
      )}

      {/* Optional ad between editorial sections — renders nothing until ads are enabled. */}
      <div className="mx-auto w-full max-w-content px-gutter empty:hidden">
        <AdSlot placement="home" />
      </div>

      {/* Scene 5: Newsletter */}
      <Section tone="white" width="narrow" aria-labelledby="newsletter-heading">
        <Reveal className="flex flex-col items-center gap-6 text-center">
          <Eyebrow>Newsletter</Eyebrow>
          <Heading id="newsletter-heading" reveal>New ideas, delivered thoughtfully</Heading>
          <Text muted>Occasional letters about new books and articles. No noise.</Text>
          <div className="w-full text-left">
            <NewsletterForm />
          </div>
        </Reveal>
      </Section>

      {/* Scene 6: Final invitation — a calm close that echoes the library's arched window. */}
      <section className="relative overflow-hidden bg-[linear-gradient(to_bottom,var(--color-white),var(--color-beige))] py-section">
        {/* The arched window drifts slower than the page — a quiet sense of depth. */}
        <Parallax distance={50} className="pointer-events-none absolute inset-0">
          <div
            aria-hidden
            className="absolute left-1/2 top-[12%] h-[80%] w-[min(60vw,22rem)] -translate-x-1/2 rounded-t-full border border-gold/40 bg-[radial-gradient(ellipse_at_50%_30%,var(--window-glow),transparent_70%)]"
          />
        </Parallax>
        <Reveal className="relative mx-auto flex max-w-narrow flex-col items-center gap-8 px-gutter text-center">
          <Heading size="h1" reveal>Your next chapter is on the shelf.</Heading>
          <Magnetic>
            <LinkButton href="/books" size="lg">
              Explore Books
            </LinkButton>
          </Magnetic>
        </Reveal>
      </section>
    </MotionProvider>
  );
}
